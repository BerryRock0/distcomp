#ifndef DC_THREAD_H
#define DC_THREAD_H

#include <stddef.h>

/*
 * Пул потоков для тяжёлого узла.
 *
 * Движок считает почти всё в matvec — умножении матрицы на вектор, — а он
 * однороден по выходу: каждый результат считается своей же цепочкой
 * сложений, в любом порядке строк. Значит, строки можно раздать потокам и
 * получить побитово тот же ответ, что и в один поток, — а машина с
 * шестнадцатью ядрами перестанет работать на одном.
 *
 * Пул один на процесс и поднимается лениво: лёгкий узел, который только
 * считает выражения, пула не получит вовсе. Сборка для микроконтроллеров
 * (DC_LITE) обходится без потоков совсем.
 */

/* Что делает поток на своём куске: элементы [from, to) из n. */
typedef void (*tp_fn)(void *arg, int from, int to);

/* Сколько потоков считать «всеми» для этой машины: DC_THREADS, если задан,
 * иначе число доступных процессоров. */
int tp_default(void);

/* Задать число потоков: 1 — считать в один поток (как было), 0 — все ядра,
 * >1 — ровно столько. Менять можно до начала работы; пул пересоздастся. */
void tp_set(int nthreads);

/* Сколько потоков будет на самом деле. */
int tp_threads(void);

/* Раздать n элементов между потоками. Если работа мелкая или пул не нужен,
 * выполняется прямо в вызывающем потоке — без всякой синхронизации.
 * Возвращает false, если элементов меньше порога и разбивать было смысла
 * нет (вызывающий сам всё выполнит). */
int tp_run(tp_fn fn, void *arg, int n);

/* Порог объёма работы, ниже которого разбивать нечего: накладные расходы
 * на синхронизацию съедают выигрыш. Считает вызывающий по объёму работы, а
 * не по числу раздаваемых кусков: кусков может быть и 1536, а работы за
 * ними — на 13 миллионов умножений. */
int tp_worthwhile(int ops);

/* Освободить пул. Вызывать необязательно: процесс всё равно завершается. */
void tp_shutdown(void);

#endif /* DC_THREAD_H */
